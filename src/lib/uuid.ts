// Supabase ids are uuids. Checked with a plain pattern rather than a strict
// RFC version check, so any id the database generates is accepted.
export const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isUuid(value: string) {
  return UUID_RE.test(value);
}
